// Diagnostic names written by the Versus message logger. The two integer widths and
// both output operations are visible at its call sites. The class and method names
// for the formatter and its text output are descriptive.
#include "versus_cldata.h"
#include <stdio.h>
#include <string.h>

namespace _STL {
    struct input_iterator_tag {};
    struct forward_iterator_tag : input_iterator_tag {};
    struct bidirectional_iterator_tag : forward_iterator_tag {};
    struct random_access_iterator_tag : bidirectional_iterator_tag {};
    struct false_type {};

    template<class T> inline random_access_iterator_tag iterator_category(const T *)
    {
        return random_access_iterator_tag();
    }

    template<class T, class Traits, class Alloc> class basic_string {
    public:
        basic_string &_M_append(const T *First, const T *Last, const forward_iterator_tag &);

        basic_string &_M_append_dispatch(const T *First, const T *Last, const false_type &)
        {
            return _M_append(First, Last, iterator_category(First));
        }

        basic_string &append(const T *First, const T *Last)
        {
            return _M_append_dispatch(First, Last, false_type());
        }

        basic_string &append(const T *Text)
        {
            return append(Text, Text + Traits::length(Text));
        }
    };

    template<> struct char_traits<char> {
        static unsigned int length(const char *Text) { return strlen(Text); }
    };
}

class DiagnosticText : public clDataText {
public:
    DiagnosticText &operator<<(const char *Text)
    {
        append(Text);
        return *this;
    }

    DiagnosticText &operator<<(unsigned int Value)
    {
        char Buffer[32];
        sprintf(Buffer, "%u", Value);
        append(Buffer);
        return *this;
    }
};

