#define DESTROY_TYPED_ARRAY(Entry) \
extern "C" void __fastcall destroy_typed_##Entry(TypedArray *array) \
{ \
    array->Remove(0, array->count); \
    if (array->data) \
        reinterpret_cast<ArrayAllocatorVirtual *>(array_allocator)->Release(array->data); \
    array->data = 0; \
    array->capacity = 0; \
    array->count = 0; \
}

