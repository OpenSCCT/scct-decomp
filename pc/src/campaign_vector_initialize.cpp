// campaign_vector_initialize.cpp -- vector allocation and initialization.
#include "campaign_vector_initialization.h"

template<class T> bool CampaignVectorStorage<T>::Initialize(size_t Count)
{
    First = 0;
    Last = 0;
    End = 0;
    if (Count == 0)
        return false;

    if (Count <= Allocator.MaxSize()) {
        T *Storage = Allocator.Allocate(Count);
        End = Storage + Count;
        First = Storage;
        Last = Storage;
    }
    return true;
}

